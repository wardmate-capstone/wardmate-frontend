import { test, expect } from '@playwright/test';
import { documentIds, mockDocumentWorkflow } from './fixtures/documentWorkflow';

test('vòng bổ sung v1 → gửi lại v2 → duyệt, không PATCH khi NEED_REVISION', async ({ page }) => {
  test.setTimeout(60_000);
  const state = await mockDocumentWorkflow(page, 'officer', 'UNDER_REVIEW');
  state.submissionStatus = 'Submitted'; state.evidenceQuantity = 2; state.checklistStatus = 'COMPLETED';
  await page.goto('/officer');
  await page.getByRole('button', { name: 'Tất cả hồ sơ', exact: true }).click();
  await page.getByRole('button', { name: 'Tiếp tục', exact: true }).click();
  await page.getByRole('button', { name: /^Nhận xét \(/ }).click();
  await page.getByLabel('Mục cần nhận xét').selectOption('/formData/a~1b~0c');
  await page.getByLabel('Nội dung nhận xét').fill('Sửa thông tin đã kê khai');
  await page.getByRole('button', { name: 'Lưu nhận xét vào hồ sơ' }).click();
  await expect.poll(() => state.comments.length).toBe(1);
  expect(state.comments[0].targetId).toBe('/formData/a~1b~0c');
  await page.getByRole('button', { name: 'Yêu cầu bổ sung', exact: true }).click();
  const revision = page.getByRole('dialog', { name: 'Yêu cầu bổ sung hồ sơ' });
  await revision.getByRole('button', { name: 'Xác nhận quyết định' }).click();
  await expect(revision.getByRole('alert')).toContainText('Nhập lý do');
  await revision.getByLabel('Lý do').fill('Rà soát lại thông tin bản khai');
  await revision.getByRole('button', { name: 'Xác nhận quyết định' }).click();
  await expect.poll(() => state.status).toBe('NEED_REVISION');
  state.actor = 'citizen';
  await page.goto('/citizen?section=dossiers_all');
  await page.getByRole('button', { name: 'Chi tiết', exact: true }).click();
  const form = page.locator(`#checklist-${documentIds.checklist}`);
  const writesBefore = state.writes.length;
  await form.getByLabel('Thay tệp Word đã điền').setInputFiles({ name: 'to-khai.docx', mimeType: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document', buffer: Buffer.from('corrected-docx') });
  await expect(form.getByText('Đã lưu bản nháp', { exact: true })).toBeVisible();
  await form.getByRole('button', { name: 'Xác nhận bản khai', exact: true }).click();
  await expect(form.getByText('Đã xác nhận', { exact: true })).toBeVisible();
  expect(state.writes.slice(writesBefore).some(x => x.path.includes('/checklists/'))).toBe(false);
  await page.getByRole('button', { name: 'Gửi lại hồ sơ đã sửa', exact: true }).first().click();
  const confirm = page.getByRole('dialog', { name: 'Xác nhận gửi lại hồ sơ' });
  await confirm.getByRole('checkbox').check();
  await confirm.getByRole('button', { name: 'Xác nhận gửi', exact: true }).click();
  await expect.poll(() => state.version).toBe(2);
  const resubmit = state.writes.find(x => x.path.endsWith('/resubmit'))!;
  expect(JSON.parse(resubmit.body).expectedVersionNumber).toBe(1);
  expect(JSON.parse(resubmit.body).checklists.map((x: { id: string }) => x.id)).toEqual([documentIds.checklist, documentIds.evidence]);
  expect(state.comments[0].status).toBe('RESOLVED');
  state.actor = 'officer';
  await page.goto('/officer');
  await page.getByRole('button', { name: 'Tất cả hồ sơ', exact: true }).click();
  await page.getByRole('button', { name: 'Review lại', exact: true }).click();
  await page.getByRole('button', { name: 'Xác nhận giấy tờ sẵn sàng', exact: true }).click();
  await page.getByRole('button', { name: 'Xác nhận quyết định' }).click();
  await expect.poll(() => state.status).toBe('DOCUMENTS_READY');
  expect(state.writes.filter(x => x.path.endsWith('/confirm-readiness'))).toHaveLength(1);
  expect(state.writes.filter(x => x.path.includes('/officer/submissions/') && /request-revision|confirm-readiness/.test(x.path))).toHaveLength(2);
  expect(state.writes.filter(x => /officer\/applications\/.+\/(request-revision|confirm-readiness)$/.test(x.path))).toHaveLength(0);
});

test('validation file chặn tệp rỗng, sai đuôi và quá 20 MiB trước upload', async ({ page }) => {
  const state = await mockDocumentWorkflow(page);
  await page.goto('/citizen?section=dossiers_all');
  await page.getByRole('button', { name: 'Chi tiết', exact: true }).click();
  const form = page.locator(`#checklist-${documentIds.checklist}`);
  const upload = form.getByLabel('Tải lên tệp Word đã điền');
  await upload.setInputFiles({ name: 'rong.docx', mimeType: 'application/octet-stream', buffer: Buffer.alloc(0) });
  await expect(form.getByRole('alert')).toContainText('không có nội dung');
  await upload.setInputFiles({ name: 'sai.pdf', mimeType: 'application/pdf', buffer: Buffer.from('abc') });
  await expect(form.getByRole('alert')).toContainText('chọn tệp DOCX');
  await upload.setInputFiles({ name: 'qua-lon.docx', mimeType: 'application/octet-stream', buffer: Buffer.alloc(20 * 1024 * 1024 + 1) });
  await expect(form.getByRole('alert')).toContainText('20 MiB');
  expect(state.writes).toHaveLength(0);
  await page.setViewportSize({ width: 360, height: 800 });
  await expect.poll(() => page.locator('.admin-workspace').evaluate(element => getComputedStyle(element).marginLeft)).toBe('0px');
  await expect.poll(() => page.locator('#citizen-main').evaluate(element => element.getBoundingClientRect().width)).toBeGreaterThan(300);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/document-validation-mobile.png', fullPage: true });
});
